package com.siamts.synapse.ui.notes

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.siamts.synapse.data.local.SessionManager
import com.siamts.synapse.data.repository.NotesRepository
import com.siamts.synapse.data.repository.NotesRepositoryImpl
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

private data class GeneratedNoteData(
    val title: String,
    val summary: String,
    val keyPoints: List<String>,
    val importantTerms: List<String>
)

/**
 * ViewModel managing AI Notes Generator input, dynamic note generation, and save state.
 */
class NotesGeneratorViewModel(
    private val notesRepository: NotesRepository = NotesRepositoryImpl(),
    private val sessionManager: SessionManager? = SessionManager.getInstanceOrNull()
) : ViewModel() {

    private val _uiState = MutableStateFlow(NotesGeneratorUiState())
    val uiState: StateFlow<NotesGeneratorUiState> = _uiState.asStateFlow()

    fun onTopicInputChanged(topic: String) {
        _uiState.update { it.copy(topicInput = topic) }
    }

    fun onGenerateNotesClicked() {
        val rawInput = _uiState.value.topicInput.trim()
        val topic = if (rawInput.isBlank()) "Artificial Intelligence Basics" else rawInput

        _uiState.update { it.copy(isGenerating = true, isSaved = false) }

        viewModelScope.launch {
            delay(400) // Brief smooth generation transition delay
            val noteData = generateNoteForTopic(topic)

            _uiState.update { current ->
                current.copy(
                    isGenerating = false,
                    noteTitle = noteData.title,
                    noteSummary = noteData.summary,
                    keyPoints = noteData.keyPoints,
                    importantTerms = noteData.importantTerms,
                    saveStatusText = "Generated by FRIDAY AI · Ready to save",
                    isSaved = false
                )
            }
        }
    }

    fun onSaveClicked() {
        viewModelScope.launch {
            val user = sessionManager?.getSessionUser()
            val userId = user?.id ?: 1
            val userEmail = user?.email ?: "student@synapse.ai"

            val title = _uiState.value.noteTitle
            val content = buildString {
                appendLine(_uiState.value.noteSummary)
                appendLine()
                appendLine("Key Points:")
                _uiState.value.keyPoints.forEach { appendLine("• $it") }
                appendLine()
                appendLine("Important Terms: " + _uiState.value.importantTerms.joinToString(", "))
            }

            val res = notesRepository.createNote(
                title = title,
                content = content,
                subjectId = null,
                chapterId = null,
                userId = userId,
                email = userEmail
            )

            if (res.isSuccess) {
                _uiState.update {
                    it.copy(
                        isSaved = true,
                        saveStatusText = "Saved to My Notes · Synced to Cloud"
                    )
                }
            } else {
                _uiState.update {
                    it.copy(
                        isSaved = false,
                        saveStatusText = "Failed to save: ${res.exceptionOrNull()?.localizedMessage}"
                    )
                }
            }
        }
    }

    fun onTabSelected(index: Int) {
        _uiState.update { it.copy(selectedTab = index) }
    }

    private fun generateNoteForTopic(topic: String): GeneratedNoteData {
        val lower = topic.lowercase()

        return when {
            lower.contains("python") || lower.contains("java") || lower.contains("code") || lower.contains("programming") || lower.contains("sql") || lower.contains("c++") -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "A comprehensive overview of key syntax rules, core paradigms, execution model, and practical implementation patterns in $topic.",
                    keyPoints = listOf(
                        "Understand fundamental data structures, scope, and memory allocation.",
                        "Apply clean modular functions, robust error handling, and type safety.",
                        "Optimize execution time complexity and algorithmic efficiency."
                    ),
                    importantTerms = listOf("Syntax", "Memory Allocation", "Recursion", "Execution Model", "Type Safety")
                )
            }

            lower.contains("math") || lower.contains("calculus") || lower.contains("algebra") || lower.contains("equation") || lower.contains("matrix") -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "A structured mathematical breakdown covering theoretical foundations, essential formulas, derivations, and step-by-step problem solving.",
                    keyPoints = listOf(
                        "Formulate equations clearly by identifying variables and constraints.",
                        "Apply standard theorems, transformation rules, and algebraic simplification.",
                        "Verify results with boundary conditions and graphical representations."
                    ),
                    importantTerms = listOf("Theorem", "Derivation", "Variable", "Transformation", "Formula")
                )
            }

            lower.contains("physics") || lower.contains("wave") || lower.contains("motion") || lower.contains("energy") || lower.contains("quantum") -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "An in-depth study of physical principles governing energy, forces, wave interactions, and measurable phenomena in $topic.",
                    keyPoints = listOf(
                        "Energy and momentum conservation laws apply across all closed systems.",
                        "Frequency, wavelength, and velocity dictate fundamental wave behavior.",
                        "Use SI unit conversions and dimensional analysis to solve field equations."
                    ),
                    importantTerms = listOf("Conservation Law", "Frequency", "Wavelength", "Velocity", "SI Units")
                )
            }

            lower.contains("chem") || lower.contains("bond") || lower.contains("reaction") || lower.contains("atom") || lower.contains("molecule") -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "Explores atomic structures, chemical bonding mechanisms, reaction dynamics, and stoichiometry in $topic.",
                    keyPoints = listOf(
                        "Valence electron configurations determine chemical bonding and reactivity.",
                        "Exothermic and endothermic reactions involve enthalpy and energy transfers.",
                        "Balance chemical equations using mole ratios and stoichiometric rules."
                    ),
                    importantTerms = listOf("Valence Electrons", "Ionic / Covalent", "Enthalpy", "Stoichiometry", "Reactivity")
                )
            }

            lower.contains("bio") || lower.contains("cell") || lower.contains("photo") || lower.contains("dna") || lower.contains("gene") -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "A biological study examining cellular mechanisms, biochemical pathways, genetic transmission, and organism functions in $topic.",
                    keyPoints = listOf(
                        "Cells utilize specialized organelles to carry out life-sustaining metabolic functions.",
                        "Genetic information encoded in DNA controls protein synthesis via transcription and translation.",
                        "Enzymes act as biological catalysts to accelerate biochemical reactions."
                    ),
                    importantTerms = listOf("Organelle", "DNA Synthesis", "Enzyme", "Metabolism", "Catalyst")
                )
            }

            else -> {
                GeneratedNoteData(
                    title = topic.replaceFirstChar { it.uppercase() },
                    summary = "A clear, AI-synthesized summary covering core definitions, key principles, practical applications, and summary insights for $topic.",
                    keyPoints = listOf(
                        "Understand the fundamental principles and scope of $topic.",
                        "Identify critical factors, key components, and functional relationships.",
                        "Apply these concepts to solve real-world problems and practical scenarios."
                    ),
                    importantTerms = listOf("Core Concepts", "Analysis", "Framework", "Implementation", "Synthesis")
                )
            }
        }
    }
}
